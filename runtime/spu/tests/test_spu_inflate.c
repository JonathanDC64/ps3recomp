#define N 3000

/* Literals and matches, and runs of one byte (overlapping copies). */
static void make_input(uint8_t* out)
{
    static const char* words[] = { "souls ", "demon ", "boletaria ", "nexus ",
                                   "archstone ", "\x00\xff", "q" };
    static const unsigned wlen[] = { 6, 6, 10, 6, 10, 2, 1 };
    uint64_t x = 12345;
    unsigned n = 0;
    uint8_t tmp[N + 64];
    while (n < N) {
        x = (x * 1103515245u + 12345u) & 0x7FFFFFFFu;
        const unsigned w = (unsigned)((x >> 16) % 7);
        memcpy(tmp + n, words[w], wlen[w]); n += wlen[w];
        if ((x >> 8) % 61 == 0) { memset(tmp + n, (int)(x & 255), 40); n += 40; }
    }
    memcpy(out, tmp, N);
}

