static uint8_t g_want[N];

static void check_stream(const char* name, const uint8_t* s, uint32_t len)
{
    static uint8_t out[N + 16];
    uint32_t got = 0;
    memset(out, 0xCC, sizeof out);
    int r = ps3_inflate_raw(out, sizeof out, s, len, &got);
    CHECK(r == 0);
    CHECK(got == N);
    CHECK(memcmp(out, g_want, N) == 0);
    CHECK(out[N] == 0xCC);                        /* nothing past the output */

    /* exactly the right capacity is enough */
    CHECK(ps3_inflate_raw(out, N, s, len, &got) == 0 && got == N);
    /* one byte short is an error, and stays inside the buffer */
    memset(out, 0xCC, sizeof out);
    CHECK(ps3_inflate_raw(out, N - 1, s, len, &got) == -2);
    CHECK(out[N - 1] == 0xCC);
    /* a stream cut short is an error */
    CHECK(ps3_inflate_raw(out, sizeof out, s, len - 3, &got) != 0);
    CHECK(ps3_inflate_raw(out, sizeof out, s, len / 2, &got) != 0);
    printf("  %-8s %4u bytes -> %u\n", name, len, N);
}

static void test_stored(void)
{
    static uint8_t s[5 + N];
    s[0] = 0x01;                                  /* BFINAL, BTYPE 00 */
    s[1] = N & 255; s[2] = N >> 8; s[3] = ~s[1]; s[4] = (uint8_t)~s[2];
    memcpy(s + 5, g_want, N);
    check_stream("stored", s, sizeof s);
    s[3] ^= 1;                                    /* LEN and NLEN disagree */
    uint8_t out[N]; uint32_t got;
    CHECK(ps3_inflate_raw(out, N, s, sizeof s, &got) == -1);
}

static void test_bad_block_type(void)
{
    const uint8_t s[] = { 0x07, 0, 0, 0 };        /* BFINAL, BTYPE 11 */
    uint8_t out[16]; uint32_t got;
    CHECK(ps3_inflate_raw(out, sizeof out, s, sizeof s, &got) == -1);
}

int main(void)
{
    make_input(g_want);
    test_stored();
    check_stream("fixed", v_fixed, sizeof v_fixed);
    check_stream("dynamic", v_dynamic, sizeof v_dynamic);
    check_stream("fast", v_fast, sizeof v_fast);
    check_stream("mixed", v_mixed, sizeof v_mixed);
    test_bad_block_type();
    printf("test_spu_inflate: %d passed, %d failed\n", g_pass, g_fail);
    return g_fail != 0;
}
