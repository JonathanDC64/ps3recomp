/*
 * Unit tests for the raw DEFLATE decoder (runtime/spu/spu_inflate.c).
 *
 * It stands in for an SPU title's zlib, so its output has to be exactly
 * zlib's: the streams below were made by zlib (scratch generator: words picked
 * by the LCG in make_input, raw deflate, -15 window bits) and each has to
 * come back byte for byte. The ways it must fail matter as much -- a stream
 * cut short, and an output buffer one byte too small -- since the SPU hook
 * hands those cases back to the title's own code instead of guessing.
 *
 * Build:
 *   clang -std=gnu17 -I include -I runtime/spu \
 *         -o /tmp/test_spu_inflate runtime/spu/tests/test_spu_inflate.c
 *
 * Exit code: 0 if all passed, 1 if any failed. Final line prints summary.
 */

