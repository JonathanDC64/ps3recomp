#!/usr/bin/env python3
"""Write libs/video/rsx_smaa_src.h: third_party/smaa/SMAA.hlsl as a C string.

The D3D12 backend compiles SMAA's shaders at run time (RSX_AA=2), so their
source has to be inside the program. This turns the vendored SMAA.hlsl into
`static const char rsx_smaa_src[]`, one string literal per line, with line
ends as LF. Run it again after SMAA.hlsl changes; tools/test_smaa_embed.py
checks that the header and the file match.

Run: python tools/smaa_embed.py [--check]
  --check  write nothing; exit 1 if the header is not what this would write
"""
import os
import sys

TOOLS = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TOOLS)
SRC = os.path.join(ROOT, "third_party", "smaa", "SMAA.hlsl")
OUT = os.path.join(ROOT, "libs", "video", "rsx_smaa_src.h")

HEAD = """\
/*
 * ps3recomp - SMAA's shader source as a C string, for the D3D12 backend's
 * SMAA pass (RSX_AA=2; the glue around it is rsx_smaa.h).
 *
 * GENERATED by tools/smaa_embed.py from third_party/smaa/SMAA.hlsl; do not
 * edit. Run the tool again after that file changes.
 *
 * SMAA is copyright (C) 2013 Jorge Jimenez, Jose I. Echevarria, Belen Masia,
 * Fernando Navarro and Diego Gutierrez, under the MIT licence: its notice is
 * at the top of the string and in third_party/smaa/LICENSE.txt.
 */
#pragma once

static const char rsx_smaa_src[] =
"""


def literal(line):
    """One source line (without its end) as a C string literal ending in \\n.
    Non-ASCII bytes are octal escapes, always three digits, so a digit after
    one cannot extend it; a '?' after a '?' is escaped so no trigraph forms."""
    out = []
    prev = ""
    for b in line:
        c = chr(b)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\t":
            out.append("\\t")
        elif c == "?" and prev == "?":
            out.append("\\?")
        elif 0x20 <= b < 0x7F:
            out.append(c)
        else:
            out.append("\\%03o" % b)
        prev = c
    return '    "' + "".join(out) + '\\n"'


def render():
    data = open(SRC, "rb").read().replace(b"\r\n", b"\n")
    lines = data.split(b"\n")
    if lines and lines[-1] == b"":
        lines.pop()
    return HEAD + "\n".join(literal(l) for l in lines) + ";\n"


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        try:
            have = open(OUT, "r", encoding="ascii", newline="").read().replace("\r\n", "\n")
        except OSError:
            have = None
        if have != text:
            print("%s is not what tools/smaa_embed.py writes from %s: run it" % (OUT, SRC))
            return 1
        print("rsx_smaa_src.h matches SMAA.hlsl")
        return 0
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d bytes of source)" % (OUT, len(open(SRC, "rb").read().replace(b"\r\n", b"\n"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
