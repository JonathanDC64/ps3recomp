/*
 * ps3recomp - the output filter for the D3D12 backend's scale to the window
 * (RSX_OUTFILTER=1): an area filter on an axis where the frame shrinks and a
 * Catmull-Rom bicubic on an axis where it grows.
 *
 * The pixel shader reads t0 (the frame) with Load, and b0 = { viewport
 * origin x, y; frame texels per window pixel x, y; frame width, height; 0, 0 }.
 */
#pragma once

/* A triangle covering the viewport, from SV_VertexID 0-2 (no vertex buffer). */
static const char rsx_outfilter_vs[] =
    "// A triangle covering the target: vertices 0, 1, 2 at (-1,1), (3,1), (-1,-3).\n"
    "float4 main(uint id : SV_VertexID) : SV_Position\n"
    "{\n"
    "    const float2 t = float2((id << 1) & 2, id & 2);\n"
    "    return float4(t * float2(2.0, -2.0) + float2(-1.0, 1.0), 0.0, 1.0);\n"
    "}\n";

static const char rsx_outfilter_ps[] =
    "// RSX_OUTFILTER=1: the game's frame scaled into the window's viewport with an\n"
    "// area filter on an axis where it shrinks (each window pixel averages the\n"
    "// texels under it) and a Catmull-Rom bicubic on an axis where it grows.\n"
    "// t0 is the frame, read with Load (no sampler). The pass writes alpha 1, as\n"
    "// the bilinear blit does.\n"
    "Texture2D<float4> src : register(t0);\n"
    "cbuffer OF : register(b0) {\n"
    "    float2 vp_org;     // the viewport's top-left corner in the window, pixels\n"
    "    float2 scale;      // frame texels per window pixel, per axis\n"
    "    float2 src_size;   // the frame's size, texels\n"
    "    float2 pad;\n"
    "};\n"
    "\n"
    "#define MAXT 12   // texels per axis at most: an area filter up to 11:1\n"
    "\n"
    "struct Axis {\n"
    "    float lo, hi;   // area: the footprint, in texels\n"
    "    float s;        // bicubic: the sample point, in texel-centre units\n"
    "    int   i0, n;    // the first texel and the number of texels\n"
    "    bool  box;\n"
    "};\n"
    "\n"
    "Axis axis_of(float q, float sc)\n"
    "{\n"
    "    Axis a;\n"
    "    const float c = q * sc;   // the frame position under this window pixel's centre\n"
    "    if (sc >= 1.0) {\n"
    "        const float h = 0.5 * min(sc, (float)(MAXT - 1));\n"
    "        a.lo = c - h;\n"
    "        a.hi = c + h;\n"
    "        a.i0 = (int)floor(a.lo);\n"
    "        a.n  = min((int)ceil(a.hi) - a.i0, MAXT);\n"
    "        a.s  = 0.0;\n"
    "        a.box = true;\n"
    "    } else {\n"
    "        a.s  = c - 0.5;\n"
    "        a.i0 = (int)floor(a.s) - 1;\n"
    "        a.n  = 4;\n"
    "        a.lo = a.hi = 0.0;\n"
    "        a.box = false;\n"
    "    }\n"
    "    return a;\n"
    "}\n"
    "\n"
    "float weight(Axis a, int i)\n"
    "{\n"
    "    if (a.box)   // the length of texel i inside the footprint\n"
    "        return max(0.0, min((float)i + 1.0, a.hi) - max((float)i, a.lo));\n"
    "    const float x = abs((float)i - a.s);   // Catmull-Rom (B = 0, C = 0.5)\n"
    "    if (x < 1.0) return 1.0 + x * x * (1.5 * x - 2.5);\n"
    "    if (x < 2.0) return -0.5 * (x - 1.0) * (x - 2.0) * (x - 2.0);\n"
    "    return 0.0;\n"
    "}\n"
    "\n"
    "float4 main(float4 pos : SV_Position) : SV_Target\n"
    "{\n"
    "    const float2 q = pos.xy - vp_org;   // inside the viewport; pixel centres at .5\n"
    "    const Axis ax = axis_of(q.x, scale.x);\n"
    "    const Axis ay = axis_of(q.y, scale.y);\n"
    "    const int2 last = int2(src_size) - 1;\n"
    "    float3 acc = 0.0;\n"
    "    float wsum = 0.0;\n"
    "    [loop] for (int j = 0; j < ay.n; j++) {\n"
    "        const int y = ay.i0 + j;\n"
    "        const float wy = weight(ay, y);\n"
    "        if (wy == 0.0) continue;\n"
    "        [loop] for (int i = 0; i < ax.n; i++) {\n"
    "            const int x = ax.i0 + i;\n"
    "            const float w = weight(ax, x) * wy;\n"
    "            acc += w * src.Load(int3(clamp(int2(x, y), 0, last), 0)).rgb;\n"
    "            wsum += w;\n"
    "        }\n"
    "    }\n"
    "    return float4(saturate(acc / max(wsum, 1e-6)), 1.0);\n"
    "}\n";
