/*
 * ps3recomp - post anti-aliasing shaders for the D3D12 backend (RSX_AA).
 *
 * FXAA-style edge smoothing: our own implementation of the algorithm Timothy
 * Lottes published in NVIDIA's FXAA white paper (2009) and talks. No NVIDIA
 * source code is used; this file is under the project's MIT licence.
 *
 * The pixel shader reads t0 (a copy of the target) with a bilinear clamp
 * sampler at s0, and b0 = { 1/width, 1/height, width, height } of the target.
 * The pipeline writes RGB only, so the target's alpha is kept.
 */
#pragma once

/* A triangle covering the target, from SV_VertexID 0-2 (no vertex buffer). */
static const char rsx_fxaa_vs[] =
    "// A triangle covering the target: vertices 0, 1, 2 at (-1,1), (3,1), (-1,-3).\n"
    "float4 main(uint id : SV_VertexID) : SV_Position\n"
    "{\n"
    "    const float2 t = float2((id << 1) & 2, id & 2);\n"
    "    return float4(t * float2(2.0, -2.0) + float2(-1.0, 1.0), 0.0, 1.0);\n"
    "}\n";

static const char rsx_fxaa_ps[] =
    "// FXAA-style edge smoothing (RSX_AA=1). Our own implementation of the\n"
    "// algorithm Timothy Lottes published in NVIDIA's FXAA white paper (2009) and\n"
    "// talks; no NVIDIA source is used.\n"
    "//\n"
    "// t0 is a copy of the target, gamma-encoded as it goes to the screen. The\n"
    "// pass writes the target's RGB only (write mask): the alpha channel is left\n"
    "// as it was, since a title may keep data there (Demon's Souls keeps its\n"
    "// depth-of-field mask in it).\n"
    "Texture2D<float4> src : register(t0);\n"
    "SamplerState lin : register(s0);   // bilinear, clamp\n"
    "cbuffer AA : register(b0) { float2 rcp_size; float2 size; };\n"
    "\n"
    "static const float kEdgeMin = 0.0625;   // a luma step below this is left alone (dark areas)\n"
    "static const float kEdgeRel = 0.125;    // ... and one below this fraction of the local maximum\n"
    "static const float kSubpix = 0.75;      // how far a one-pixel feature is softened\n"
    "#define AA_STEPS 10\n"
    "static const float kStep[AA_STEPS] = { 1.0, 1.0, 1.0, 1.0, 1.5, 2.0, 2.0, 2.0, 4.0, 8.0 };\n"
    "\n"
    "float luma_of(float3 c) { return dot(c, float3(0.299, 0.587, 0.114)); }\n"
    "float luma_at(float2 uv) { return luma_of(src.SampleLevel(lin, uv, 0).rgb); }\n"
    "\n"
    "float4 main(float4 pos : SV_Position) : SV_Target\n"
    "{\n"
    "    const float2 uv = pos.xy * rcp_size;   // this pixel's centre\n"
    "    const float3 rgbM = src.SampleLevel(lin, uv, 0).rgb;\n"
    "    const float lM = luma_of(rgbM);\n"
    "    const float lN = luma_of(src.SampleLevel(lin, uv, 0, int2(0, -1)).rgb);\n"
    "    const float lS = luma_of(src.SampleLevel(lin, uv, 0, int2(0, 1)).rgb);\n"
    "    const float lW = luma_of(src.SampleLevel(lin, uv, 0, int2(-1, 0)).rgb);\n"
    "    const float lE = luma_of(src.SampleLevel(lin, uv, 0, int2(1, 0)).rgb);\n"
    "    const float lMin = min(lM, min(min(lN, lS), min(lW, lE)));\n"
    "    const float lMax = max(lM, max(max(lN, lS), max(lW, lE)));\n"
    "    const float range = lMax - lMin;\n"
    "    if (range < max(kEdgeMin, lMax * kEdgeRel))\n"
    "        return float4(rgbM, 1.0);   // no edge here\n"
    "    const float lNW = luma_of(src.SampleLevel(lin, uv, 0, int2(-1, -1)).rgb);\n"
    "    const float lNE = luma_of(src.SampleLevel(lin, uv, 0, int2(1, -1)).rgb);\n"
    "    const float lSW = luma_of(src.SampleLevel(lin, uv, 0, int2(-1, 1)).rgb);\n"
    "    const float lSE = luma_of(src.SampleLevel(lin, uv, 0, int2(1, 1)).rgb);\n"
    "\n"
    "    // Which way the edge runs: second differences down each column (large\n"
    "    // across a horizontal edge) against those along each row.\n"
    "    const float edgeH = abs(lNW - 2.0 * lW + lSW) + 2.0 * abs(lN - 2.0 * lM + lS) + abs(lNE - 2.0 * lE + lSE);\n"
    "    const float edgeV = abs(lNW - 2.0 * lN + lNE) + 2.0 * abs(lW - 2.0 * lM + lE) + abs(lSW - 2.0 * lS + lSE);\n"
    "    const bool horz = edgeH >= edgeV;\n"
    "\n"
    "    // The pixel across the edge: the neighbour with the larger step.\n"
    "    const float lNeg = horz ? lN : lW;\n"
    "    const float lPos = horz ? lS : lE;\n"
    "    const float gNeg = abs(lNeg - lM);\n"
    "    const float gPos = abs(lPos - lM);\n"
    "    float across = horz ? rcp_size.y : rcp_size.x;\n"
    "    float lPair;   // the luma halfway across the edge\n"
    "    if (gNeg >= gPos) {\n"
    "        across = -across;\n"
    "        lPair = 0.5 * (lNeg + lM);\n"
    "    } else {\n"
    "        lPair = 0.5 * (lPos + lM);\n"
    "    }\n"
    "    const float gStop = 0.25 * max(gNeg, gPos);\n"
    "\n"
    "    // Walk both ways along the edge, between the two rows of pixels (bilinear\n"
    "    // taps there average them), until the luma leaves lPair: the ends.\n"
    "    float2 onEdge = uv;\n"
    "    if (horz) onEdge.y += 0.5 * across;\n"
    "    else      onEdge.x += 0.5 * across;\n"
    "    const float2 along = horz ? float2(rcp_size.x, 0.0) : float2(0.0, rcp_size.y);\n"
    "    float2 pA = onEdge - along * kStep[0];\n"
    "    float2 pB = onEdge + along * kStep[0];\n"
    "    float dA = luma_at(pA) - lPair;\n"
    "    float dB = luma_at(pB) - lPair;\n"
    "    bool endA = abs(dA) >= gStop;\n"
    "    bool endB = abs(dB) >= gStop;\n"
    "    [loop] for (int i = 1; i < AA_STEPS && !(endA && endB); i++) {\n"
    "        if (!endA) { pA -= along * kStep[i]; dA = luma_at(pA) - lPair; endA = abs(dA) >= gStop; }\n"
    "        if (!endB) { pB += along * kStep[i]; dB = luma_at(pB) - lPair; endB = abs(dB) >= gStop; }\n"
    "    }\n"
    "\n"
    "    // Move toward the pixel across the edge, more the nearer this pixel is to\n"
    "    // the nearer end -- if that end is where the edge turns, which is when\n"
    "    // the luma there lies on the other side of lPair from this pixel's.\n"
    "    const float distA = horz ? uv.x - pA.x : uv.y - pA.y;\n"
    "    const float distB = horz ? pB.x - uv.x : pB.y - uv.y;\n"
    "    const float dNear = distA < distB ? dA : dB;\n"
    "    const float edgeBlend = ((dNear < 0.0) != (lM < lPair)) ? 0.5 - min(distA, distB) / (distA + distB) : 0.0;\n"
    "\n"
    "    // A pixel that stands out from its 3x3 neighbourhood (a feature one pixel\n"
    "    // wide, which the walk cannot follow) is softened as well.\n"
    "    const float mean = (2.0 * (lN + lS + lW + lE) + (lNW + lNE + lSW + lSE)) * (1.0 / 12.0);\n"
    "    float sub = saturate(abs(mean - lM) / range);\n"
    "    sub = (-2.0 * sub + 3.0) * sub * sub;\n"
    "    const float subBlend = sub * sub * kSubpix;\n"
    "\n"
    "    const float t = max(edgeBlend, subBlend);\n"
    "    float2 at = uv;\n"
    "    if (horz) at.y += t * across;\n"
    "    else      at.x += t * across;\n"
    "    return float4(src.SampleLevel(lin, at, 0).rgb, 1.0);\n"
    "}\n";
